ALTER TABLE users ADD INDEX IF NOT EXISTS idx_users_program (program_id);
ALTER TABLE users ADD CONSTRAINT fk_users_program FOREIGN KEY (program_id) REFERENCES academic_programs(id) ON DELETE SET NULL;

